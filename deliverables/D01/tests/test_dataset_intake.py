"""Temporary synthetic fixtures; no SMPL run, physical dictionary or training data."""
from copy import deepcopy
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

BASE=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(BASE/'scripts'))
from intake_dataset import inspect_dataset, dictionary_errors, digest
from prepare_manifest import prepare


class DatasetIntakeTests(unittest.TestCase):
    def setUp(self):
        self.tmp=tempfile.TemporaryDirectory();self.addCleanup(self.tmp.cleanup)
        self.root=Path(self.tmp.name)
        self.dictionary_path=self.root/'dictionary.json';self.config_path=self.root/'collection.json'
        def variable(index):
            return dict(index=index,name=f'fixture_{index}',unit='fixture_unit',
                        coordinate='synthetic_absolute',source_reference='synthetic-test-only')
        self.dictionary=dict(schema_version='D01Variables/0.1',environment='Atropine',
                             observation=[variable(0),variable(1)],action=[variable(0)],
                             review=dict(reviewed_by='automated-test-fixture',reviewed_on='2026-11-12',
                                         source_reference='not a real physical dictionary'))
        self.dictionary_path.write_text(json.dumps(self.dictionary))
        self.config_path.write_text(json.dumps({'synthetic_fixture':True}))
        self.manifest=json.loads((BASE/'examples/data_manifest.draft.json').read_text())
        self.manifest.update(status='ready_for_review',collection_config_sha256=digest(self.config_path),
                             variable_dictionary_sha256=digest(self.dictionary_path),
                             permission_evidence='synthetic fixture generated by this test only')
        self.rows={}
        for index,split in enumerate(('train','validation','test')):
            eid=f'fixture-{index}'
            self.rows[eid]=[dict(schema_version='D01Step/0.1',episode_id=eid,step_index=step,
                                simulation_time=float(step),simulation_time_unit='s',
                                collected_at=f'2026-11-12T06:00:0{step}+00:00',
                                observation_before=[0.0,0.0],observation_after=[0.0,0.0],
                                candidate_action=[0.0],executed_action=[0.0],executed=True,
                                state_version_before=step+1,state_version_after=step+2,
                                reward=0.0,terminated=False,truncated=False,
                                execution_status='completed',failure_reason=None) for step in range(2)]
            artifact=dict(path=f'{eid}.jsonl',sha256='1'*64,source_kind='synthetic',derived_from=[eid],
                          generator_version='test_dataset_intake/1',alignment_max_error_steps=0,
                          label_free_input_confirmed=True)
            episode=dict(episode_id=eid,lineage_group=eid,split=split,environment='Atropine',
                         environment_config_sha256=digest(self.config_path),seed=index,
                         initial_state_sha256=hashlib.sha256(f'fixture-{index}'.encode()).hexdigest(),
                         scenario_id='synthetic-fixture',step_count=2,label_summary='normal',
                         label_source='synthetic-fixture',event_start_step=0,event_end_step=0,
                         iforest_train=split=='train',artifacts=dict(timeseries=[artifact],visual=[],text=[]))
            self.manifest['episodes'].append(episode)
        self.sync()

    def sync(self):
        for episode in self.manifest['episodes']:
            eid=episode['episode_id'];artifact=episode['artifacts']['timeseries'][0]
            path=self.root/artifact['path']
            path.write_text(''.join(json.dumps(row)+'\n' for row in self.rows[eid]))
            artifact['sha256']=digest(path)

    def inspect(self):
        self.sync()
        return inspect_dataset(self.manifest,self.root,self.config_path,self.dictionary_path)

    def bad(self,text):
        result=self.inspect()
        self.assertFalse(result['passed'])
        self.assertTrue(any(text in error for error in result['errors']),result)

    def test_valid_structure(self):
        result=self.inspect();self.assertTrue(result['passed'],result)
        self.assertEqual(sum(r['executed_calls'] for r in result['episodes']),6)
        self.assertIn('human review',result['scope'])

    def test_dictionary_required_indices_and_units(self):
        for mutate in (lambda d:d['observation'][0].update(index=2),
                       lambda d:d['action'][0].update(unit='UNKNOWN'),
                       lambda d:d['observation'][1].update(name='fixture_0')):
            value=deepcopy(self.dictionary);mutate(value)
            self.assertTrue(dictionary_errors(value))

    def test_dictionary_environment(self):
        self.manifest['episodes'][0]['environment']='mAb';self.bad('environment does not match')

    def test_dictionary_file_hash(self):
        self.dictionary_path.write_text(json.dumps(dict(self.dictionary,environment='mAb')))
        self.bad('dictionary hash mismatch')

    def test_config_file_hash(self):
        self.config_path.write_text('{}');self.bad('configuration hash mismatch')

    def test_bad_dictionary_declaration(self):
        self.dictionary['review']['reviewed_on']='not-a-date'
        self.dictionary_path.write_text(json.dumps(self.dictionary))
        self.manifest['variable_dictionary_sha256']=digest(self.dictionary_path)
        self.bad('reviewed_on')

    def test_episode_identity(self):
        self.rows['fixture-0'][0]['episode_id']='other';self.bad('episode_id mismatch')

    def test_record_order(self):
        self.rows['fixture-0'][1]['step_index']=0;self.bad('step_index')

    def test_record_count(self):
        self.rows['fixture-0'].pop();self.bad('record count differs')

    def test_observation_dimensions(self):
        self.rows['fixture-0'][0]['observation_before']=[0.0];self.bad('dimensions differ')

    def test_executed_action_dimensions(self):
        self.rows['fixture-0'][0]['executed_action']=[0,0];self.bad('dimensions differ')

    def test_nonfinite_json(self):
        self.rows['fixture-0'][0]['reward']=float('nan');self.bad('nonfinite JSON')

    def test_boolean_is_not_numeric(self):
        self.rows['fixture-0'][0]['candidate_action']=[True];self.bad('row schema')

    def test_missing_row_field(self):
        del self.rows['fixture-0'][0]['simulation_time_unit'];self.bad('row schema')

    def test_unknown_fields_label_leakage(self):
        self.rows['fixture-0'][0]['anomaly_label']='leaked';self.bad('row schema')

    def test_completed_requires_outputs(self):
        self.rows['fixture-0'][0]['observation_after']=None;self.bad('completed execution requires')

    def test_completed_cannot_have_error(self):
        self.rows['fixture-0'][0]['failure_reason']='failure';self.bad('cannot carry failure_reason')

    def test_rejected_cannot_execute(self):
        self.rows['fixture-0'][0].update(execution_status='rejected',failure_reason='blocked')
        self.bad('cannot be rejected')

    def test_unexecuted_cannot_fake_outputs(self):
        self.rows['fixture-0'][0].update(executed=False,execution_status='rejected',failure_reason='blocked')
        self.bad('must not invent')

    def test_rejected_valid_no_advance(self):
        rows=self.rows['fixture-0']
        rows[0].update(executed=False,executed_action=None,observation_after=None,reward=None,
                       execution_status='rejected',failure_reason='fixture refusal',state_version_after=1)
        rows[1].update(state_version_before=1,state_version_after=2)
        self.assertTrue(self.inspect()['passed'])

    def test_failed_needs_reason(self):
        self.rows['fixture-0'][0]['execution_status']='failed';self.bad('needs a failure reason')

    def test_version_continuity(self):
        self.rows['fixture-0'][1].update(state_version_before=20,state_version_after=21)
        self.bad('state_version discontinuity')

    def test_no_records_after_termination(self):
        self.rows['fixture-0'][0]['terminated']=True;self.bad('record after terminal')

    def test_termination_flags_exclusive(self):
        self.rows['fixture-0'][1].update(terminated=True,truncated=True);self.bad('cannot both be true')

    def test_simulation_clock(self):
        self.rows['fixture-0'][0]['simulation_time']=2;self.bad('simulation time moved backwards')

    def test_collection_clock(self):
        self.rows['fixture-0'][1]['collected_at']='2026-11-12T05:00:00Z';self.bad('collection time moved backwards')

    def test_unsupported_clock_unit(self):
        self.rows['fixture-0'][0]['simulation_time_unit']='min';self.bad('row schema')

    def test_prepare_hashes_draft_and_preserves_original(self):
        spec=deepcopy(self.manifest)
        spec['collection_config_sha256']='0'*64
        spec['episodes'][0]['artifacts']['timeseries'][0]['sha256']='0'*64
        result=prepare(spec,self.root,self.config_path,self.dictionary_path)
        self.assertEqual(result['status'],'draft')
        self.assertEqual(spec['status'],'ready_for_review')
        self.assertEqual(result['collection_config_sha256'],digest(self.config_path))
        self.assertEqual(spec['collection_config_sha256'],'0'*64)

    def test_prepare_refuses_path_escape(self):
        self.manifest['episodes'][0]['artifacts']['timeseries'][0]['path']='../outside'
        with self.assertRaises(ValueError):prepare(self.manifest,self.root,self.config_path,self.dictionary_path)

    def test_prepare_cli_never_overwrites_spec(self):
        spec=self.root/'spec.json';spec.write_text(json.dumps(self.manifest));original=spec.read_bytes()
        result=subprocess.run([sys.executable,str(BASE/'scripts/prepare_manifest.py'),str(spec),'--root',str(self.root),
                               '--config',str(self.config_path),'--dictionary',str(self.dictionary_path),
                               '--output',str(spec)],capture_output=True)
        self.assertNotEqual(result.returncode,0);self.assertEqual(spec.read_bytes(),original)

    def test_intake_cli_failure_exit(self):
        manifest=self.root/'manifest.json';manifest.write_text(json.dumps(dict(self.manifest,status='draft')))
        result=subprocess.run([sys.executable,str(BASE/'scripts/intake_dataset.py'),str(manifest),'--root',str(self.root),
                               '--config',str(self.config_path),'--dictionary',str(self.dictionary_path)],capture_output=True)
        self.assertEqual(result.returncode,1);self.assertFalse(json.loads(result.stdout)['passed'])

    def test_intake_cli_success_report(self):
        manifest=self.root/'manifest.json';manifest.write_text(json.dumps(self.manifest))
        report=self.root/'review.json'
        result=subprocess.run([sys.executable,str(BASE/'scripts/intake_dataset.py'),str(manifest),'--root',str(self.root),
                               '--config',str(self.config_path),'--dictionary',str(self.dictionary_path),
                               '--report',str(report)],capture_output=True)
        self.assertEqual(result.returncode,0,result.stderr)
        self.assertTrue(json.loads(report.read_text())['passed'])

    def test_intake_report_cannot_overwrite_input(self):
        manifest=self.root/'manifest.json';manifest.write_text(json.dumps(self.manifest))
        original=manifest.read_bytes()
        result=subprocess.run([sys.executable,str(BASE/'scripts/intake_dataset.py'),str(manifest),'--root',str(self.root),
                               '--config',str(self.config_path),'--dictionary',str(self.dictionary_path),
                               '--report',str(manifest)],capture_output=True)
        self.assertNotEqual(result.returncode,0)
        self.assertEqual(manifest.read_bytes(),original)

    def test_prepare_cli_produces_unapproved_draft(self):
        spec=self.root/'spec.json';spec.write_text(json.dumps(self.manifest))
        output=self.root/'draft.json'
        result=subprocess.run([sys.executable,str(BASE/'scripts/prepare_manifest.py'),str(spec),'--root',str(self.root),
                               '--config',str(self.config_path),'--dictionary',str(self.dictionary_path),
                               '--output',str(output)],capture_output=True)
        self.assertEqual(result.returncode,0,result.stderr)
        draft=json.loads(output.read_text());self.assertEqual(draft['status'],'draft')
        self.assertFalse(inspect_dataset(draft,self.root,self.config_path,self.dictionary_path)['passed'])

    def test_normal_label_cannot_declare_anomaly_interval(self):
        self.manifest['episodes'][0]['event_end_step']=1
        self.bad('normal episode must not declare')

    def test_collection_time_requires_timezone(self):
        self.rows['fixture-0'][0]['collected_at']='2026-11-12T06:00:00'
        self.assertFalse(self.inspect()['passed'])


if __name__=='__main__':unittest.main()
